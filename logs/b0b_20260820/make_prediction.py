"""Emit logs/b0b_20260820/PREDICTION.txt before any B0b build runs."""
import sys
from pathlib import Path

sys.path.insert(0, r"c:\Users\lychee\Desktop\FPGA\.github-upload\sw")
import tme_cycle_model as M  # noqa: E402

DIRECT = [(12, 10, 4, 4), (4, 4, 4, 4)]
MANIFEST = [
    (216, 13, 216, 8), (230, 13, 216, 8), (231, 13, 216, 8), (232, 13, 216, 8),
    (130, 21, 100, 12), (131, 21, 100, 12), (132, 21, 100, 12),
    (114, 27, 20, 12), (115, 27, 20, 12),
    (47, 21, 16, 12), (47, 21, 16, 12), (88, 39, 24, 16),
]
ROWS = DIRECT + MANIFEST

out = []
w = out.append
w("PRIORITY 6 (B0b) -- PREDICTIONS, REGISTERED BEFORE THE FIRST BUILD")
w("=" * 70)
w("")
w("Committed before run_hls_b0b.tcl was executed for any solution.  B2's")
w("evidence had to be relabelled because its 'pre-registration' rested on")
w("file timestamps that turned out to post-date the cosim report; the fix")
w("recorded there was to put predictions in git BEFORE the run.  This is")
w("that, for B0b.")
w("")
w("THREE SOLUTIONS, TWO DIFFERENCES")
w("-" * 70)
w("  b2ctl   the shipped core (tme_top.b2.cpp + correlation_core.b2.cpp),")
w("          byte-identical to what logs/b2_20260819 measured.")
w("  shadow  b2ctl PLUS the hoisted vertically-reused window-statistics")
w("          pass, compared at every result position.  Nothing removed.")
w("  b0b     the hoisted pass only; the repeated statistics loops deleted.")
w("")
w("  D1 = shadow - b2ctl   what the count pass COSTS")
w("  D2 = b0b    - shadow  what the repeated loops cost, i.e. what the")
w("                        model's window-statistics attribution is worth")
w("")
w("PREDICTION 1 -- THE CONTROL IS INTACT")
w("-" * 70)
w("Every b2ctl transaction must equal tme_cycle_model.cycles(..., 'B2')")
w("exactly.  If it does not, the pair is not a pair and nothing below is")
w("attributable.  Zero free parameters.")
w("")
w("PREDICTION 2 -- THE COUNT PASS (D1)")
w("-" * 70)
w("Iterations, already derived in tme_cycle_model.b0b_count_pass_iterations")
w("and unchanged by anything in this session:")
w("")
w("    S = th + 2*(rh - 1)            scans per invocation")
w("    I = S * pw                     iterations, since one scan is")
w("                                   tw + (rw - 1) = pw iterations")
w("")
w("The FROZEN endpoints assume D1 = N*I for N in {1, 3} and nothing else.")
w("That is the thing being tested, and it is expected to be optimistic:")
w("B1's projection missed by T+1 per (output row, template row) and B2's by")
w("3T-1, both in the direction that flattered the change.  NO CORRECTION IS")
w("CARRIED FORWARD -- neither shape is assumed to recur.  What is registered")
w("here is the SHAPE to be fitted:")
w("")
w("    D1 = S * (pw + k) + m          two free parameters")
w("")
w("k is per-scan overhead (pipeline flush of the two II=1 loops plus the")
w("call), m is per-invocation.  k = m = 0 is exactly the frozen II=1")
w("endpoint.")
w("")
_S = sorted({t[3] + 2 * (t[1] - t[3]) for t in ROWS})
_P = sorted({t[0] for t in ROWS})
w("COUNT THE CONSTRAINTS HONESTLY.  Under this shape the residual against")
w("S*pw depends on S alone, so transactions sharing an S restate one")
w("equation.  The suite spans S in {%s}" % ", ".join(str(x) for x in _S))
w("-- %d independent equations against two free parameters, so %d surplus"
  % (len(_S), len(_S) - 2))
w("constraints.  The other %d transactions sit at an already-constrained S"
  % (len(ROWS) - len(_S)))
w("with a DIFFERENT pw (the suite spans pw in {%s}),"
  % ", ".join(str(x) for x in _P))
w("so they test that the residual is a function of S alone rather than")
w("adding information about (k, m).")
w("")
w("PREDICTION 3 -- THE REMOVAL (D2)")
w("-" * 70)
w("tme_cycle_model attributes the per-(output row, template row) cost as")
w("")
w("    template-row staging          2*tw + 3")
w("    window statistics             tw + rw + 21   <- what B0b removes")
w("    correlation writeback/control 2*rw + 8")
w("    accum_rows FSM transition     1")
w("")
w("Only the SUM of those four has ever been measured.  The split has not.")
w("D2 is the first direct measurement of one of its terms, and it predicts")
w("")
w("    D2 = -rh * th * (tw + rw + 21)")
w("")
w("with zero free parameters.  A miss here is a finding about the model's")
w("decomposition, not about B0b: the other three terms would have to absorb")
w("it, and 'fully attributed' would stop being true.")
w("")
w("PER-TRANSACTION TABLE (the b1 cosim suite: 2 direct + 12 manifest)")
w("-" * 70)
w("%-3s %-20s %8s %8s %10s %12s %14s"
  % ("#", "pw x ph / tw x th", "S", "I", "b2 cycles", "D1 at II=1", "D2 predicted"))
for i, (pw, ph, tw, th) in enumerate(ROWS):
    rw, rh = pw - tw + 1, ph - th + 1
    S = th + 2 * (rh - 1)
    I = M.b0b_count_pass_iterations(pw, ph, tw, th)
    assert I == S * pw, (I, S, pw)
    b2 = M.cycles(pw, ph, tw, th, "B2")
    d2 = -rh * th * (tw + rw + 21)
    w("%-3d %-20s %8d %8d %10d %12d %14d"
      % (i, "%dx%d / %dx%d" % (pw, ph, tw, th), S, I, b2, I, d2))
w("")
w("WHOLE-WORKLOAD CONSEQUENCE, AND HOW TO RECOMPUTE IT")
w("-" * 70)
w("The frozen s/page endpoints are")
w("    B0b base (deletion only)   %.6f" % M.FROZEN["s_per_page_at_125mhz"]["B0b_base"])
w("    B0b at II=1                %.12f" % M.FROZEN["s_per_page_at_125mhz"]["B0b_at_1_cyc"])
w("    B0b at II=3                %.12f" % M.FROZEN["s_per_page_at_125mhz"]["B0b_at_3_cyc"])
w("Those sum a per-trial term over 20,680 modelled trials at 125 MHz.  They")
w("are NOT page times: no page has been run on any hardware at any clock.")
w("If the fit gives (k, m) != (0, 0) the endpoints move, and the replacement")
w("is B2 + D2 + D1 summed over the same workload -- not one of the two")
w("frozen numbers with a correction bolted on.")
w("")
w("WHAT THIS PREDICTION DOES NOT COVER")
w("-" * 70)
w("  * the clock.  A cosim latency is a zero-stall RTL schedule; whether the")
w("    hoisted pass still closes 8.000 ns is a routed result.  B2 closed it")
w("    with +0.011710 ns, so B0b starts with 12 ps of margin on a path")
w("    inside correlation_core that B0b does not itself edit.")
w("  * silicon.  Nothing here has run on a board.")
w("  * the shadow build's own latency as a B0b figure.  shadow is b2ctl plus")
w("    a pass; it is SLOWER than b2ctl by construction and is not a variant")
w("    anyone would ship.")
w("")

